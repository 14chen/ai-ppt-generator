/**
 * Generate the mini program's theme files from the single source of truth
 * (`web/src/player/runtime.js`, read through server/themes.js).
 *
 * Why generate instead of using CSS custom properties in WXSS: WeChat's docs
 * never confirm `var(--x)` support, so the mini program uses plain class-based
 * theming, which always works. Generating it keeps it drift-free — and
 * `tests/unit/miniprogram.test.js` fails if these files go stale.
 *
 * Usage: node scripts/gen-miniprogram-themes.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { allThemes } from '../server/themes.js';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT_JS = path.join(ROOT, 'miniprogram', 'utils', 'themes.generated.js');
const OUT_WXSS = path.join(ROOT, 'miniprogram', 'styles', 'themes.wxss');

const themes = allThemes();

/* ------------------------------------------------------------------ JS ---- */

const js = `/* AUTO-GENERATED by scripts/gen-miniprogram-themes.mjs — DO NOT EDIT.
 * Source of truth: web/src/player/runtime.js (themes are shared with the web UI,
 * the exported HTML and the PPTX export so they can never drift).
 * Regenerate with: npm run sync:themes
 */
module.exports = {
  THEMES: ${JSON.stringify(themes, null, 2)},
  themeIds: ${JSON.stringify(themes.map((t) => t.id))}
};
`;

/* ---------------------------------------------------------------- WXSS ---- */

/** [selector-suffix, css-property, value(themeVars, theme)] */
const RULES = [
  ['&', 'background-color', (v) => v['ppt-page-bg']],
  ['.s-slide', 'background-image', (v) => `linear-gradient(158deg, ${v['ppt-slide-bg']} 0%, ${v['ppt-slide-bg2']} 100%)`],
  ['.s-slide', 'color', (v) => v['ppt-text']],
  ['.s-slide', 'box-shadow', (v, t) => `0 10rpx 36rpx rgba(0, 0, 0, ${t.dark ? 0.55 : 0.16})`],
  ['.s-text', 'color', (v) => v['ppt-text']],
  ['.s-dim', 'color', (v) => v['ppt-dim']],
  ['.s-accent-text', 'color', (v) => v['ppt-accent']],
  ['.s-accent-bg', 'background-color', (v) => v['ppt-accent']],
  ['.s-accent2-bg', 'background-color', (v) => v['ppt-accent2']],
  ['.s-chip', 'background-color', (v) => v['ppt-chip-bg']],
  ['.s-chip', 'border-color', (v) => v['ppt-line']],
  ['.s-card', 'background-color', (v) => v['ppt-chip-bg']],
  ['.s-card', 'border-color', (v) => v['ppt-line']],
  ['.s-quote', 'background-color', (v) => v['ppt-quote-bg']],
  ['.s-quote', 'border-color', (v) => v['ppt-line']],
  ['.s-divider', 'background-color', (v) => v['ppt-line']],
  ['.s-dot', 'background-color', (v) => v['ppt-dim']],
  ['.s-dot-active', 'background-color', (v) => v['ppt-accent']],
  ['.s-glow-a', 'background-color', (v) => v['ppt-accent']],
  ['.s-glow-b', 'background-color', (v) => v['ppt-accent2']],
  ['.s-btn', 'background-color', (v) => v['ppt-chip-bg']],
  ['.s-btn', 'border-color', (v) => v['ppt-line']],
  ['.s-btn', 'color', (v) => v['ppt-text']],
  ['.s-on-accent', 'color', (v, t) => (t.dark ? '#08131F' : '#FFFFFF')],
  ['.s-progress-fill', 'background-color', (v) => v['ppt-accent']]
];

const blocks = themes.map((t) => {
  const v = t.vars;
  const lines = [
    `/* ${t.label} (${t.id})${t.dark ? ' · dark' : ' · light'} */`
  ];
  const grouped = new Map();
  for (const [suffix, prop, get] of RULES) {
    const selector = suffix === '&' ? `.t-${t.id}` : `.t-${t.id} ${suffix}`;
    if (!grouped.has(selector)) grouped.set(selector, []);
    grouped.get(selector).push(`  ${prop}: ${get(v, t)};`);
  }
  for (const [selector, decls] of grouped) {
    lines.push(`${selector} {`, ...decls, '}');
  }
  return lines.join('\n');
});

const wxss = `/* AUTO-GENERATED by scripts/gen-miniprogram-themes.mjs — DO NOT EDIT.
 * Class-based themes (no CSS custom properties: WXSS support is not documented).
 * Source of truth: web/src/player/runtime.js -> server/themes.js
 * Regenerate with: npm run sync:themes
 */
${blocks.join('\n\n')}
`;

fs.mkdirSync(path.dirname(OUT_JS), { recursive: true });
fs.mkdirSync(path.dirname(OUT_WXSS), { recursive: true });
fs.writeFileSync(OUT_JS, js, 'utf8');
fs.writeFileSync(OUT_WXSS, wxss, 'utf8');

console.log(`themes    : ${themes.map((t) => `${t.id}(${t.label})`).join(', ')}`);
console.log(`written   : ${path.relative(ROOT, OUT_JS)}  (${Buffer.byteLength(js)} bytes)`);
console.log(`written   : ${path.relative(ROOT, OUT_WXSS)}  (${Buffer.byteLength(wxss)} bytes)`);
